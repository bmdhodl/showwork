"""Run the test command recorded by showwork init.

Command checks can only invoke ``python <script under the project root>``.
This script is that script. It reads ``.showwork/contract.json`` and runs
``test_command`` as an argv list (no shell). Edit the contract to change
the command; do not edit this file to manufacture a passing close.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
CONTRACT = HERE / "contract.json"


def main() -> int:
    try:
        data = json.loads(CONTRACT.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        print(f"showwork default check: cannot read {CONTRACT}: {exc}", file=sys.stderr)
        return 2
    command = data.get("test_command") if isinstance(data, dict) else None
    if not isinstance(command, list) or not command or not all(isinstance(item, str) for item in command):
        print("showwork default check: test_command must be a non-empty list of strings",
              file=sys.stderr)
        return 2
    argv = list(command)
    if Path(argv[0]).name.lower() in {"python", "python3", "python.exe"}:
        argv[0] = sys.executable
    try:
        result = subprocess.run(argv, cwd=str(ROOT))
    except FileNotFoundError:
        print(f"showwork default check: command not found: {argv[0]}", file=sys.stderr)
        return 127
    except OSError as exc:
        print(f"showwork default check: {exc}", file=sys.stderr)
        return 2
    return int(result.returncode)


if __name__ == "__main__":
    raise SystemExit(main())
